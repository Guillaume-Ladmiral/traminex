"""RP6b: live-R goldens for seqcta (competing-trajectory-analysis converter).

Anchors traminex ``seqcta`` to TraMineRextras 0.6.9. Goldens generated by
``scripts/r_goldens/make_goldens_seqcta.R``.
"""

from __future__ import annotations

import numpy as np
from corestats_fixtures import fixture_a
from r_goldens_utils import R_GOLDEN_ATOL, load_golden

from traminex.stats_p2 import seqcta


def _matrix(df, x, subseq):
    real_alph = [x.alphabet[i] for i in range(len(x.alphabet)) if i not in (x.void_code, x.nr_code)]
    code = {s: k + 1 for k, s in enumerate(real_alph)}
    tcols = [f"T{k}" for k in range(1, subseq + 1)]
    out = np.empty((len(df), 4 + subseq), dtype=float)
    out[:, 0] = df["id"].to_numpy(dtype=float)
    out[:, 1] = df["time"].to_numpy(dtype=float)
    out[:, 2] = df["event"].to_numpy(dtype=float)
    out[:, 3] = df["lastobs"].to_numpy(dtype=float)
    for j, c in enumerate(tcols):
        out[:, 4 + j] = [code.get(v, np.nan) if isinstance(v, str) else np.nan for v in df[c]]
    return out


def test_seqcta_given():
    x = fixture_a()
    df = seqcta(x, subseq=2, time=[4, 3, 5, 2], event=[True, False, True, True])
    np.testing.assert_allclose(
        _matrix(df, x, 2), load_golden("seqcta_A_given"), rtol=0, atol=R_GOLDEN_ATOL, equal_nan=True
    )


def test_seqcta_initial_state():
    x = fixture_a()
    df = seqcta(x, subseq=2, initial_state="A")
    np.testing.assert_allclose(
        _matrix(df, x, 2), load_golden("seqcta_A_init"), rtol=0, atol=R_GOLDEN_ATOL, equal_nan=True
    )
