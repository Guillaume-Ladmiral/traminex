"""R-golden parity for seqdss / seqdur / seqivolatility (roadmap Phase 1).

Fixtures A and B are void-free and rectangular; fixture C is ragged (short rows
right-padded with the structural void "%"). All are constructed with an explicit
alphabet so state codes align with R's seqasnum (0-based over the alphabet).
Goldens are generated by scripts/r_goldens/make_goldens_seqdss_seqdur.R against
TraMineR 2.2-14; missing/void/right-pad cells are dumped as the sentinel -1.
"""

from __future__ import annotations

import numpy as np
from r_goldens_utils import R_GOLDEN_ATOL, load_golden

from traminex.format import seqdef
from traminex.sequences import STSList
from traminex.stats_complexity import seqdss, seqdur, seqivolatility

ALPH_A = ["A", "B", "C", "D"]
SEQS_A = [
    ["A", "A", "B", "C", "C", "C"],
    ["A", "B", "B", "B", "C", "A"],
    ["D", "D", "D", "D", "D", "D"],
    ["A", "B", "A", "B", "A", "B"],
]
ALPH_B = ["A", "B", "C"]
SEQS_B = [
    ["A", "A", "*", "B", "B", "C"],
    ["*", "A", "A", "A", "*", "*"],
    ["A", "*", "A", "B", "B", "B"],
    ["C", "C", "C", "C", "C", "C"],
]
# Fixture C is ragged: short rows are padded with the void symbol "%". (In the R
# generator the same rows are padded with "*" and right="DEL" turns the trailing
# "*" into void; here we write the void directly so traminex encodes it as void.)
ALPH_C = ["A", "B", "C"]
SEQS_C = [
    ["A", "A", "B", "C", "C", "C"],
    ["A", "B", "B", "%", "%", "%"],
    ["A", "*", "A", "B", "%", "%"],
    ["C", "C", "%", "%", "%", "%"],
]


def _fixture_a():
    return seqdef(np.array(SEQS_A, dtype=object), alphabet=ALPH_A)


def _fixture_b():
    return seqdef(np.array(SEQS_B, dtype=object), alphabet=ALPH_B, nr="*")


def _fixture_c():
    # void="%" is the seqdef default; "*" -> nr, "%" -> void.
    return seqdef(np.array(SEQS_C, dtype=object), alphabet=ALPH_C, nr="*")


def _dur_with_sentinel(out: np.ndarray) -> np.ndarray:
    out = np.asarray(out, dtype=float).copy()
    out[np.isnan(out)] = -1
    return out


def test_seqdur_fixture_a_matches_r():
    golden = load_golden("seqdur_A")
    actual = _dur_with_sentinel(seqdur(_fixture_a()))
    assert actual.shape == golden.shape
    np.testing.assert_allclose(actual, golden, rtol=0, atol=R_GOLDEN_ATOL)


def test_seqdur_fixture_b_with_and_without_missing():
    sd = _fixture_b()
    np.testing.assert_allclose(
        _dur_with_sentinel(seqdur(sd, include_missing=False)),
        load_golden("seqdur_B_nomiss"),
        rtol=0,
        atol=R_GOLDEN_ATOL,
    )
    np.testing.assert_allclose(
        _dur_with_sentinel(seqdur(sd, include_missing=True)),
        load_golden("seqdur_B_miss"),
        rtol=0,
        atol=R_GOLDEN_ATOL,
    )


def test_seqdur_fixture_c_ragged_with_and_without_missing():
    sd = _fixture_c()
    np.testing.assert_allclose(
        _dur_with_sentinel(seqdur(sd, include_missing=False)),
        load_golden("seqdur_C_nomiss"),
        rtol=0,
        atol=R_GOLDEN_ATOL,
    )
    np.testing.assert_allclose(
        _dur_with_sentinel(seqdur(sd, include_missing=True)),
        load_golden("seqdur_C_miss"),
        rtol=0,
        atol=R_GOLDEN_ATOL,
    )


def _dss_codes_with_sentinel(out: STSList) -> np.ndarray:
    """Map a seqdss STSList back to seqasnum-style codes (void/pad -> -1)."""
    data = out.data.astype(int).copy().astype(float)
    if out.void_code is not None:
        data[out.data == out.void_code] = -1
    return data


def test_seqdss_fixture_a_matches_r():
    out = seqdss(_fixture_a())
    actual = _dss_codes_with_sentinel(out)
    golden = load_golden("seqdss_A")
    assert actual.shape == golden.shape
    np.testing.assert_allclose(actual, golden, rtol=0, atol=R_GOLDEN_ATOL)


def test_seqdss_fixture_b_with_and_without_missing():
    sd = _fixture_b()
    np.testing.assert_allclose(
        _dss_codes_with_sentinel(seqdss(sd, include_missing=False)),
        load_golden("seqdss_B_nomiss"),
        rtol=0,
        atol=R_GOLDEN_ATOL,
    )
    np.testing.assert_allclose(
        _dss_codes_with_sentinel(seqdss(sd, include_missing=True)),
        load_golden("seqdss_B_miss"),
        rtol=0,
        atol=R_GOLDEN_ATOL,
    )


def test_seqdss_fixture_c_ragged_with_and_without_missing():
    sd = _fixture_c()
    np.testing.assert_allclose(
        _dss_codes_with_sentinel(seqdss(sd, include_missing=False)),
        load_golden("seqdss_C_nomiss"),
        rtol=0,
        atol=R_GOLDEN_ATOL,
    )
    np.testing.assert_allclose(
        _dss_codes_with_sentinel(seqdss(sd, include_missing=True)),
        load_golden("seqdss_C_miss"),
        rtol=0,
        atol=R_GOLDEN_ATOL,
    )


def test_seqivolatility_fixture_a_matches_r():
    sd = _fixture_a()
    actual = np.array(
        [
            seqivolatility(sd, w=0.5, adjust=True),
            seqivolatility(sd, w=0.5, adjust=False),
            seqivolatility(sd, w=0.0, adjust=True),
            seqivolatility(sd, w=1.0, adjust=True),
        ]
    )
    np.testing.assert_allclose(actual, load_golden("seqivol_A"), rtol=0, atol=R_GOLDEN_ATOL)


