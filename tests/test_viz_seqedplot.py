"""RP7 follow-up: seqedplot (TraMineRextras event-duration plot) structure tests.

Structure-tested (not pixel) against the R-golden'd producing series
(seqedplot_surv_* / seqedplot_haz_*, generated by make_goldens_seqedplot.R):
one coloured curve per non-ignored event; survival step vertices == the KM
series starting at (0,1); hazard abscissae == the period upper edges and the
ordinates == the binned means; grouping yields one panel per level. Each is
mutation-checked (suppress a curve via ignore; weights load-bearing for hazard).
"""

from __future__ import annotations

import matplotlib

matplotlib.use("Agg")

import numpy as np
import pandas as pd
import pytest
from r_goldens_utils import R_GOLDEN_ATOL, load_golden

from traminex.events import seqecreate
from traminex.visualization.plots import seqedplot


# ---- fixtures mirroring make_goldens_seqedplot.R -------------------------- #
def _surv_eseq():
    tse = pd.DataFrame(
        {
            "id": ["s1", "s1", "s2", "s3", "s3", "s4", "s4", "s5"],
            "timestamp": [1, 3, 2, 1, 4, 1, 3, 2],
            "event": ["A", "B", "A", "B", "A", "A", "A", "B"],
        }
    )
    e = seqecreate(tse)
    e.lengths = [5, 5, 6, 4, 5]
    return e


def _haz_tse():
    return pd.DataFrame(
        {
            "id": [
                "s1",
                "s1",
                "s1",
                "s2",
                "s2",
                "s3",
                "s3",
                "s4",
                "s4",
                "s4",
                "s5",
                "s5",
                "s6",
                "s6",
            ],
            "timestamp": [1, 3, 5, 2, 4, 1, 6, 1, 2, 4, 3, 5, 5, 2],
            "event": ["A", "A", "B", "A", "B", "B", "A", "A", "A", "A", "B", "B", "A", "B"],
        }
    )


def _haz_eseq(weighted=True):
    e = seqecreate(_haz_tse())
    if weighted:
        e.weights = [1.0, 2.0, 0.5, 1.5, 2.5, 1.0]
    return e


# ---- survival ------------------------------------------------------------- #
def test_survival_one_step_curve_per_event_matches_golden():
    fig, axes = seqedplot(_surv_eseq(), type="survival")
    assert len(axes) == 1
    ax = axes[0]
    assert len(ax.lines) == 2  # one curve per kept event (A, B)
    for line, tag in zip(ax.lines, ("seqedplot_surv_A", "seqedplot_surv_B")):
        g = load_golden(tag)  # time, n.risk, n.event, surv, std.err
        expected = np.vstack([[0.0, 1.0], np.column_stack([g[:, 0], g[:, 3]])])
        # R runs each curve on to its last time within xlim = ages (here 4;
        # tests/test_r_goldens_survival_extent.py, TX-AUD-20261011-026).
        if expected[-1, 0] < 4:
            expected = np.vstack([expected, [4.0, expected[-1, 1]]])
        np.testing.assert_allclose(line.get_xydata(), expected, rtol=0, atol=R_GOLDEN_ATOL)
    # survival curves never rise and start at (0, 1)
    for line in ax.lines:
        ys = line.get_ydata()
        assert ys[0] == 1.0
        assert np.all(np.diff(ys) <= 1e-12)


def test_survival_axis_is_zero_to_one():
    fig, axes = seqedplot(_surv_eseq(), type="survival")
    lo, hi = axes[0].get_ylim()
    assert lo == 0.0 and 1.0 <= hi <= 1.1


def test_survival_ignore_suppresses_a_curve():
    fig, axes = seqedplot(_surv_eseq(), type="survival", ignore=["B"])
    labels = [ln.get_label() for ln in axes[0].lines]
    assert labels == ["A"]  # the B curve is gone (mutation)


def test_survival_requires_observation_time():
    e = seqecreate(  # lengths unset (all -1)
        pd.DataFrame({"id": ["s1", "s1"], "timestamp": [1, 2], "event": ["A", "B"]})
    )
    with pytest.raises(ValueError, match="observation time"):
        seqedplot(e, type="survival")


# ---- hazard --------------------------------------------------------------- #
def test_hazard_lines_match_golden_ungrouped():
    fig, axes = seqedplot(_haz_eseq(), type="hazard", breaks=5)
    ax = axes[0]
    g = load_golden("seqedplot_haz_all_b5")  # rows: onx, A, B
    assert len(ax.lines) == 2
    for line, row in zip(ax.lines, (1, 2)):
        np.testing.assert_allclose(line.get_xdata(), g[0], rtol=0, atol=R_GOLDEN_ATOL)
        np.testing.assert_allclose(line.get_ydata(), g[row], rtol=0, atol=R_GOLDEN_ATOL)


def test_hazard_grouped_one_panel_per_level():
    group = ["X", "X", "X", "Y", "Y", "Y"]
    fig, axes = seqedplot(_haz_eseq(), type="hazard", group=group, breaks=5)
    assert len(axes) == 2  # one panel per group level
    g = load_golden("seqedplot_haz_b5")  # rows: onx, g1_A, g1_B, g2_A, g2_B
    for gi, ax in enumerate(axes):
        assert len(ax.lines) == 2
        for ei, line in enumerate(ax.lines):
            np.testing.assert_allclose(line.get_xdata(), g[0], rtol=0, atol=R_GOLDEN_ATOL)
            np.testing.assert_allclose(
                line.get_ydata(), g[1 + gi * 2 + ei], rtol=0, atol=R_GOLDEN_ATOL
            )


def test_hazard_weights_are_load_bearing():
    # Mutation: dropping weights changes the hazard ordinates (-> would be red).
    fig_w, axes_w = seqedplot(_haz_eseq(weighted=True), type="hazard", breaks=5)
    fig_u, axes_u = seqedplot(_haz_eseq(weighted=False), type="hazard", breaks=5)
    # weighted line A == the weighted golden, and differs from the unit-weight render
    g = load_golden("seqedplot_haz_all_b5")
    np.testing.assert_allclose(axes_w[0].lines[0].get_ydata(), g[1], rtol=0, atol=R_GOLDEN_ATOL)
    assert not np.allclose(axes_w[0].lines[0].get_ydata(), axes_u[0].lines[0].get_ydata())


# ---- shared guards -------------------------------------------------------- #
def test_invalid_type_raises():
    with pytest.raises(ValueError, match="survival.*hazard|type"):
        seqedplot(_haz_eseq(), type="density")


def test_ignore_removing_all_events_raises():
    with pytest.raises(ValueError, match="At least one event"):
        seqedplot(_haz_eseq(), type="hazard", ignore=["A", "B"])


def test_per_event_colours_are_distinct():
    fig, axes = seqedplot(_haz_eseq(), type="hazard", breaks=5)
    colours = [ln.get_color() for ln in axes[0].lines]
    assert colours[0] != colours[1]


def test_survival_all_censored_event_renders_flat():
    # An event that never occurs renders flat at survival 1 (no downward step).
    tse = pd.DataFrame(
        {
            "id": ["s1", "s1", "s2", "s3"],
            "timestamp": [1, 3, 2, 1],
            "event": pd.Categorical(["A", "B", "A", "B"], categories=["A", "B", "C"]),
        }
    )
    e = seqecreate(tse)
    e.lengths = [5, 5, 6]
    fig, axes = seqedplot(e, type="survival")
    # the C curve (third kept event) never drops below 1
    labels = [ln.get_label() for ln in axes[0].lines]
    c_line = axes[0].lines[labels.index("C")]
    assert np.all(c_line.get_ydata() == 1.0)
