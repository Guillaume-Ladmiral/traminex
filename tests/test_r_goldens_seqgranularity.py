"""RP6b: live-R goldens for seqgranularity (time-granularity coarsening).

Anchors traminex ``seqgranularity`` to TraMineRextras 0.6.9. Goldens generated by
``scripts/r_goldens/make_goldens_seqgranularity.R``.
"""

from __future__ import annotations

import numpy as np
from corestats_fixtures import fixture_a, fixture_c
from r_goldens_utils import R_GOLDEN_ATOL, load_golden

from traminex.stats_p2 import seqgranularity


def _codes(res, x):
    # 1-based code into the ORIGINAL real alphabet; void / nr -> NaN (R match against alphabet).
    real_alph = [x.alphabet[i] for i in range(len(x.alphabet)) if i not in (x.void_code, x.nr_code)]
    code = {s: k + 1 for k, s in enumerate(real_alph)}
    labels = np.array(res.alphabet, dtype=object)
    out = np.empty(res.data.shape, dtype=float)
    for r in range(res.data.shape[0]):
        for c in range(res.data.shape[1]):
            out[r, c] = code.get(labels[res.data[r, c]], np.nan)
    return out


def _check(x, tspan, method, name):
    res = seqgranularity(x, tspan=tspan, method=method)
    np.testing.assert_allclose(
        _codes(res, x), load_golden(name), rtol=0, atol=R_GOLDEN_ATOL, equal_nan=True
    )


def test_seqgran_A_first():
    _check(fixture_a(), 3, "first", "seqgran_A_first")


def test_seqgran_A_last():
    _check(fixture_a(), 3, "last", "seqgran_A_last")


def test_seqgran_A_first_valid():
    _check(fixture_a(), 3, "first.valid", "seqgran_A_firstvalid")


def test_seqgran_A_last_valid():
    _check(fixture_a(), 3, "last.valid", "seqgran_A_lastvalid")


def test_seqgran_A_mostfreq():
    _check(fixture_a(), 3, "mostfreq", "seqgran_A_mostfreq")


def test_seqgran_C_last():
    _check(fixture_c(), 2, "last", "seqgran_C_last")


def test_seqgran_C_mostfreq():
    _check(fixture_c(), 2, "mostfreq", "seqgran_C_mostfreq")
