def _seqient_r2_rows():
    with (R_GOLDENS_DIR / "seqient_r2_base.csv").open(encoding="utf-8", newline="") as stream:
        return list(csv.DictReader(stream))


def _seqient_declared_missing_fixture():
    x = seqdef(np.asarray(SEQS_A, dtype=object)[:, :4], alphabet=ALPH_A)
    x.alphabet.append(x.nr)
    x.nr_code = len(x.alphabet) - 1
    if x.labels is not None:
        x.labels.append(x.nr)
    return x


def test_seqient_r2_bases_and_natural_log_normalization_match_r():
    rows = _seqient_r2_rows()
    cases = {row["case"] for row in rows}
    assert cases == {
        "dense_base2.71828182845905_normFALSE",
        "dense_base2.71828182845905_normTRUE",
        "dense_base2_normFALSE",
        "dense_base2_normTRUE",
        "dense_base10_normFALSE",
        "dense_base10_normTRUE",
        "declared_unobserved_missing_wm0",
        "declared_unobserved_missing_wm1",
    }
    for case in cases:
        expected_rows = [row for row in rows if row["case"] == case]
        first = expected_rows[0]
        x = _seqient_declared_missing_fixture() if case.startswith("declared") else _fa()
        actual = seqient(
            x,
            base=float(first["base"]),
            norm=first["norm"] == "TRUE",
            include_missing=first["with_missing"] == "TRUE",
        )
        expected = np.asarray([float(row["value"]) for row in expected_rows])
        np.testing.assert_allclose(actual, expected, rtol=0, atol=R_GOLDEN_ATOL, equal_nan=True)


