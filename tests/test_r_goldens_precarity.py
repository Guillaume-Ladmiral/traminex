    sd = seqdef(np.array(seqs_m, dtype=object), alphabet=["A", "B", "C"])
    golden = load_golden("seqmaintokens_M_k2").ravel().astype(int) - 1
    np.testing.assert_array_equal(np.asarray(seqmaintokens(sd, k=2)), golden)


