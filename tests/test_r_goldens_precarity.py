def _seqlogp_stationary():
    return np.asarray(
        [
            [0.55, 0.25, 0.15, 0.05],
            [0.10, 0.60, 0.20, 0.10],
            [0.15, 0.15, 0.60, 0.10],
            [0.20, 0.10, 0.10, 0.60],
        ],
        dtype=float,
    )


def _seqlogp_timevarying():
    model = np.zeros((4, 4, 5), dtype=float)
    for time in range(1, 6):
        for source in range(1, 5):
            values = ((source + 2 * np.arange(1, 5) + time) % 7) + 1
            model[source - 1, :, time - 1] = values / values.sum()
    return model


def _seqlogp_edge_fixture():
    return seqdef(
        np.asarray(
            [
                ["A", "B", "C"],
                ["B", "C", "D"],
                ["C", "D", "A"],
                ["D", "A", "B"],
            ],
            dtype=object,
        ),
        alphabet=ALPH_A,
    )


def _seqlogp_edge_model():
    model = np.full((4, 4), 0.25, dtype=float)
    model[0, 1] = 0
    model[1, 2] = np.nan
    model[2, 3] = np.inf
    model[3, 0] = 0.5
    return model


def _seqlogp_case_arguments(case, first):
    if case == "edge_zero_nan_inf":
        x = _seqlogp_edge_fixture()
        prob = _seqlogp_edge_model()
        begin = np.asarray([0, np.nan, np.inf, 0.5])
    else:
        x = (
            _fb()
            if first["include_missing"] == "TRUE" and not case.startswith("phantom")
            else _fa()
        )
        x.weights = np.asarray([1.5, 2.0, 0.5, 3.0])
        prob = {
            "trate": "trate",
            "freq": "freq",
            "matrix": _seqlogp_stationary(),
            "array": _seqlogp_timevarying(),
        }[first["prob"]]
        begin = {
            "freq": "freq",
            "global.freq": "global.freq",
            "array": np.asarray([0.1, 0.2, 0.3, 0.4]),
        }[first["begin"]]
    return x, {
        "prob": prob,
        "time_varying": first["time_varying"] == "TRUE",
        "begin": begin,
        "weighted": first["weighted"] == "TRUE",
        "include_missing": first["include_missing"] == "TRUE",
    }


def test_seqlogp_r2_probability_model_matrix_matches_r():
    rows = _seqlogp_r2_rows()
    cases = list(dict.fromkeys(row["case"] for row in rows))
    assert len(cases) == 74
