def _r2_fixture(tag):
    if tag in {"B", "Bw"}:
        x = _fb()
    else:
        values = np.asarray(SEQS_A, dtype=object)
        if tag == "Aswap":
            values = values.copy()
            b = values == "B"
            c = values == "C"
            values[b] = "C"
            values[c] = "B"
        x = seqdef(values, alphabet=ALPH_A)
    if tag.endswith("w"):
        x.weights = np.asarray([1.5, 2.0, 0.5, 3.0])
    return x


def _r2_state_kwargs(row):
    order = row["state_order"].split("|") if row["state_order"] else None
    equiv = (
        [group.split("+") for group in row["state_equiv"].split(";")]
        if row["state_equiv"]
        else None
    )
    return order, equiv


def _r2_correction(value):
    if not value:
        return None
    values = np.asarray([float(item) for item in value.split("|")])
    return float(values[0]) if values.size == 1 else values


def test_seqprecarity_r2_state_model_cross_product_matches_r_without_mutation():
    rows = [row for row in _precarity_order_r2_rows() if row["function"] == "seqprecarity"]
    cases = list(dict.fromkeys(row["case"] for row in rows))
    assert len(cases) == 10
    for case in cases:
        expected_rows = [row for row in rows if row["case"] == case]
        first = expected_rows[0]
        x = _r2_fixture(first["fixture"])
        before = x.copy()
        state_order, state_equiv = _r2_state_kwargs(first)
        actual = seqprecarity(
            x,
            correction=_r2_correction(first["correction"]),
            otto=float(first["otto"]),
            a=float(first["a"]),
            b=float(first["b"]),
            method=first["method"],
            state_order=state_order,
            state_equiv=state_equiv,
            include_missing=first["with_missing"] == "TRUE",
            penalized=first["penalized"],
            weight_type=first["weight_type"],
            pow=float(first["pow"]),
            border_effect=float(first["border_effect"]),
        )
        expected = np.asarray([float(row["value"]) for row in expected_rows])
        np.testing.assert_allclose(actual, expected, rtol=0, atol=R_GOLDEN_ATOL)
        np.testing.assert_array_equal(x.data, before.data)
        assert x.alphabet == before.alphabet
        if x.weights is not None:
            np.testing.assert_array_equal(x.weights, before.weights)


