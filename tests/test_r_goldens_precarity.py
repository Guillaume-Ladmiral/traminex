@pytest.mark.parametrize("include_missing", [False, True])
@pytest.mark.parametrize("k", [1, 2, 3, 4, 5, 8])
def test_seqmaintokens_indices_address_the_public_alphabet(k, include_missing):
    # The documented R idiom `alphabet(sd)[seqmaintokens(sd)]` must translate: every
    # returned index must be a valid position in alphabet(x, with_missing=...).
    for sd in (_fa(), _fb(), _fc()):
        states = alphabet(sd, with_missing=include_missing)
        idx = np.asarray(seqmaintokens(sd, k=k, include_missing=include_missing))
        assert idx.size >= 1
        assert int(idx.min()) >= 0
        assert int(idx.max()) < len(
            states
        ), f"index {int(idx.max())} is out of range for alphabet {states}"
        assert len([states[i] for i in idx]) == idx.size


