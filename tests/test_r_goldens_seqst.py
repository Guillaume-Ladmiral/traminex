"""R-golden parity for seqST (Elzinga turbulence) void/missing faithfulness.

Pins traminex.seqST to TraMineR 2.2-14 across rectangular void-free (A, B) and
ragged void-padded (C) fixtures, for norm in {False, True} x include_missing in
{False, True}, type=1. These guard the fix for the defect where seqST counted
structural void as a state under include_missing=True (and leaked nr/void into
the norm reference alphabet). Fixtures match tests/test_r_goldens_seqdss_seqdur.py;
goldens are generated by scripts/r_goldens/make_goldens_seqst.R.
"""

from __future__ import annotations

import numpy as np
from r_goldens_utils import R_GOLDEN_ATOL, load_golden

from traminex.format import seqdef
from traminex.stats_complexity import seqST, turbulence_exact

ALPH_A = ["A", "B", "C", "D"]
SEQS_A = [
    ["A", "A", "B", "C", "C", "C"],
    ["A", "B", "B", "B", "C", "A"],
    ["D", "D", "D", "D", "D", "D"],
    ["A", "B", "A", "B", "A", "B"],
]
ALPH_B = ["A", "B", "C"]
SEQS_B = [
    ["A", "A", "*", "B", "B", "C"],
    ["*", "A", "A", "A", "*", "*"],
    ["A", "*", "A", "B", "B", "B"],
    ["C", "C", "C", "C", "C", "C"],
]
# Fixture C is ragged: short rows padded with the void symbol "%".
ALPH_C = ["A", "B", "C"]
SEQS_C = [
    ["A", "A", "B", "C", "C", "C"],
    ["A", "B", "B", "%", "%", "%"],
    ["A", "*", "A", "B", "%", "%"],
    ["C", "C", "%", "%", "%", "%"],
]


def _fixture_a():
    return seqdef(np.array(SEQS_A, dtype=object), alphabet=ALPH_A)


def _fixture_b():
    return seqdef(np.array(SEQS_B, dtype=object), alphabet=ALPH_B, nr="*")


def _fixture_c():
    return seqdef(np.array(SEQS_C, dtype=object), alphabet=ALPH_C, nr="*")


def _st_rows(sd, type: int = 1) -> np.ndarray:
    """Stack seqST for the four (norm, include_missing) modes, matching the golden."""
    return np.array(
        [
            seqST(sd, norm=False, include_missing=False, type=type),
            seqST(sd, norm=False, include_missing=True, type=type),
            seqST(sd, norm=True, include_missing=False, type=type),
            seqST(sd, norm=True, include_missing=True, type=type),
        ]
    )


def test_seqST_fixture_a_matches_r():
    np.testing.assert_allclose(
        _st_rows(_fixture_a()), load_golden("seqST_A"), rtol=0, atol=R_GOLDEN_ATOL
    )


def test_seqST_fixture_b_matches_r():
    np.testing.assert_allclose(
        _st_rows(_fixture_b()), load_golden("seqST_B"), rtol=0, atol=R_GOLDEN_ATOL
    )


def test_seqST_fixture_c_ragged_matches_r():
    np.testing.assert_allclose(
        _st_rows(_fixture_c()), load_golden("seqST_C"), rtol=0, atol=R_GOLDEN_ATOL
    )


def test_seqST_type2_fixture_a_matches_r():
    np.testing.assert_allclose(
        _st_rows(_fixture_a(), type=2), load_golden("seqST_A_t2"), rtol=0, atol=R_GOLDEN_ATOL
    )


def test_seqST_type2_fixture_b_matches_r():
    np.testing.assert_allclose(
        _st_rows(_fixture_b(), type=2), load_golden("seqST_B_t2"), rtol=0, atol=R_GOLDEN_ATOL
    )


def test_seqST_type2_fixture_c_ragged_matches_r():
    np.testing.assert_allclose(
        _st_rows(_fixture_c(), type=2), load_golden("seqST_C_t2"), rtol=0, atol=R_GOLDEN_ATOL
    )


def test_turbulence_exact_is_mean_of_seqST_on_ragged_missing():
    # turbulence_exact wraps seqST; on a ragged+missing fixture it must equal the
    # plain mean of the (now void-faithful) per-sequence seqST values.
    sd = _fixture_c()
    per = seqST(sd, norm=False, include_missing=True, type=1)
    assert turbulence_exact(sd, norm=False, include_missing=True, type=1) == np.mean(per)
