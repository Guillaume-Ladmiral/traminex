"""RP6b: live-R goldens for seqindic_dyn (dynamic/windowed sequence indicator).

Anchors traminex ``seqindic_dyn`` to TraMineRextras 0.6.9 ``seqindic.dyn``. Goldens
generated by ``scripts/r_goldens/make_goldens_seqindic_dyn.R``.
"""

from __future__ import annotations

import numpy as np
from corestats_fixtures import fixture_a, fixture_c
from r_goldens_utils import R_GOLDEN_ATOL, load_golden

from traminex.stats_utils import seqindic_dyn


def _check(actual, name):
    np.testing.assert_allclose(
        np.asarray(actual, dtype=float),
        load_golden(name),
        rtol=0,
        atol=R_GOLDEN_ATOL,
        equal_nan=True,
    )


def test_seqindic_dyn_A_cplx_slide():
    _check(seqindic_dyn(fixture_a(), indic="cplx", window_size=0.5), "seqindic_dyn_A_cplx_slide")


def test_seqindic_dyn_A_cplx_incr():
    _check(
        seqindic_dyn(fixture_a(), indic="cplx", window_size=0.5, sliding=False),
        "seqindic_dyn_A_cplx_incr",
    )


def test_seqindic_dyn_A_trans_slide():
    _check(seqindic_dyn(fixture_a(), indic="trans", window_size=2), "seqindic_dyn_A_trans_slide")


def test_seqindic_dyn_C_cplx_slide():
    _check(seqindic_dyn(fixture_c(), indic="cplx", window_size=0.5), "seqindic_dyn_C_cplx_slide")
