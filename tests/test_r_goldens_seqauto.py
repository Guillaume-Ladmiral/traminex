"""RP6b: live-R golden for seqauto (state autocorrelation by lag).

Anchors traminex ``seqauto`` to TraMineRextras 0.6.9. Golden generated by
``scripts/r_goldens/make_goldens_seqauto.R``.
"""

from __future__ import annotations

import numpy as np
from corestats_fixtures import fixture_a
from r_goldens_utils import R_GOLDEN_ATOL, load_golden

from traminex.stats_p2 import seqauto


def test_seqauto_A_order2():
    np.testing.assert_allclose(
        seqauto(fixture_a(), order=2), load_golden("seqauto_A_o2"), rtol=0, atol=R_GOLDEN_ATOL
    )
