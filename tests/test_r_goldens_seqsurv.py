"""RP6b: live-R goldens for seqsurv (weighted Kaplan-Meier spell survival).

Anchors traminex ``seqsurv`` to TraMineRextras 0.6.9 (which uses ``survival::survfit``).
Goldens generated by ``scripts/r_goldens/make_goldens_seqsurv.R``.

Both goldens pin all five metrics (time/n.risk/n.event/surv/std.err). The unweighted
std.err is the textbook Greenwood (NaN at surv=0); for fractional weights R sets
robust=TRUE, so the weighted std.err is the infinitesimal-jackknife SE (0 at surv=0),
which traminex now reproduces to machine precision (audit F6).
"""

from __future__ import annotations

import csv
from functools import lru_cache
from pathlib import Path

import numpy as np
import pandas as pd
import pytest
from corestats_fixtures import fixture_a
from r_goldens_utils import R_GOLDEN_ATOL, load_golden

from traminex import seqdef
from traminex.stats_p2 import SeqSurv, seqsurv

R2_CASES = Path(__file__).with_name("r_goldens") / "seqsurv_r2_cases.csv"
R2_ERRORS = Path(__file__).with_name("r_goldens") / "seqsurv_r2_errors.txt"
R2_MESSAGES = Path(__file__).with_name("r_goldens") / "seqsurv_r2_messages.txt"
SUMMARY_COLUMNS = [
    "states",
    "time",
    "n.risk",
    "n.event",
    "surv",
    "std.err",
    "lower",
    "upper",
    "curve_axis",
    "state",
    "group",
]


def _stacked(res, x, with_se):
    rows = []
    for st in res.states:
        arr = res.curves[st]
        if len(arr) == 0:
            continue
        code = list(x.alphabet).index(st) + 1
        for r in arr:
            row = [code, r[0], r[1], r[2], r[3]]
            if with_se:
                row.append(r[4])
            rows.append(row)
    return np.array(rows, dtype=float)


def test_seqsurv_A_unweighted():
    x = fixture_a()
    np.testing.assert_allclose(
        _stacked(seqsurv(x), x, with_se=True),
        load_golden("seqsurv_A"),
        rtol=0,
        atol=R_GOLDEN_ATOL,
        equal_nan=True,
    )


def test_seqsurv_A_weighted_robust_se():
    # Fractional weights -> R robust=TRUE -> infinitesimal-jackknife std.err (0 at
    # surv=0), now reproduced to machine precision. Audit F6.
    x = fixture_a(weighted=True)
    np.testing.assert_allclose(
        _stacked(seqsurv(x), x, with_se=True),
        load_golden("seqsurv_A_w"),
        rtol=0,
        atol=R_GOLDEN_ATOL,
        equal_nan=True,
    )


# R2 complete state/group survival contract ----------------------------------
@lru_cache(maxsize=1)
def _r2_rows():
    with R2_CASES.open(encoding="utf-8", newline="") as stream:
        return tuple(csv.DictReader(stream))


def _case_rows(case):
    return [row for row in _r2_rows() if row["case"] == case]


def _section(rows, name):
    return sorted(
        (row for row in rows if row["section"] == name),
        key=lambda row: (int(row["row"]), row["curve"]),
    )


def _number(value):
    return np.nan if value in {"NA", "NaN", ""} else float(value)


def _texts(rows, section):
    return [row["text"] for row in _section(rows, section)]


def _scalar_text(rows, section):
    return _section(rows, section)[0]["text"]


def _scalar_value(rows, section):
    return _number(_section(rows, section)[0]["value"])


def _expected_curve(rows, key):
    selected = [row for row in _section(rows, "survival") if row["curve"] == key]
    if not selected:
        return np.empty((0, 7), dtype=float)
    return np.asarray(
        [
            [
                _number(row["time"]),
                _number(row["n_risk"]),
                _number(row["n_event"]),
                _number(row["surv"]),
                _number(row["std_err"]),
                _number(row["lower"]),
                _number(row["upper"]),
            ]
            for row in selected
        ],
        dtype=float,
    )


def _r2_fixture(*, weighted=False):
    data = [
        ["A", "A", "B", "B", "C", "C"],
        ["A", "B", "B", "B", "C", "A"],
        ["D", "D", "D", "D", "D", "D"],
        ["A", "B", "A", "B", "A", "B"],
        ["A", "A", None, "C", None, None],
        ["B", "B", "C", "C", "C", "B"],
    ]
    return seqdef(
        data,
        alphabet=["A", "B", "C", "D"],
        labels=["Alpha", "Beta", "Gamma", "No exit"],
        cpal=["#111111", "#333333", "#777777", "#AAAAAA"],
        weights=[1, 2.5, 0.5, 3, 1.5, 2] if weighted else None,
        xtstep=2,
        tick_last=True,
    )


def _groups():
    return pd.Categorical(
        ["early", "late", "noexit", "early", "late", "early"],
        categories=["late", "early", "noexit"],
        ordered=True,
    )


def _one_group():
    return pd.Categorical(["solo"] * 6, categories=["solo"], ordered=True)


def _run_r2_case(case):
    if case == "state_all_unweighted":
        return seqsurv(_r2_fixture())
    if case == "state_all_weighted":
        return seqsurv(_r2_fixture(weighted=True))
    if case == "state_one_B":
        return seqsurv(_r2_fixture(), state="B")
    if case == "state_subset_C_A":
        return seqsurv(_r2_fixture(), state=["C", "A"])
    if case == "state_one_group":
        return seqsurv(_r2_fixture(), groups=_one_group(), state=["D", "A"])
    if case == "group_all_unweighted":
        return seqsurv(_r2_fixture(), groups=_groups(), per_state=True)
    if case == "group_one_state_weighted":
        return seqsurv(_r2_fixture(weighted=True), groups=_groups(), per_state=True, state="B")
    if case == "group_subset_A_C":
        return seqsurv(_r2_fixture(), groups=_groups(), per_state=True, state=["C", "A"])
    if case == "missing_false":
        return seqsurv(_r2_fixture(), state=["A", "B", "C"], with_missing=False)
    raise AssertionError(f"unknown case {case}")


def _assert_r2_result(case, result):
    rows = _case_rows(case)
    keys = [row["curve"] for row in _section(rows, "curve")]
    assert isinstance(result.curves, dict)
    assert list(result.curves) == keys
    assert result.strata == keys
    for key in keys:
        actual = result.curves[key]
        assert actual.ndim == 2 and actual.shape[1] == 7
        np.testing.assert_allclose(
            actual,
            _expected_curve(rows, key),
            rtol=0,
            atol=1e-12,
            equal_nan=True,
        )

    assert result.curve_axis == _scalar_text(rows, "curve_axis")
    assert result.states == _texts(rows, "state")
    assert result.groups == _texts(rows, "group")
    assert result.ltext == _texts(rows, "ltext")
    expected_cpal = _texts(rows, "cpal")
    assert result.cpal == (None if expected_cpal == ["NULL"] else expected_cpal)
    assert result.xtstep == int(_scalar_value(rows, "xtstep"))
    assert result.tick_last is bool(int(_scalar_value(rows, "tick_last")))
    # The R-side ``survival`` version is deliberately NOT a fixture field. It is a
    # recommended package supplied by the R installation, so the isolated oracle
    # library cannot pin it and recording it as data made the documented two-pass
    # provenance proof fail on any machine whose ``survival`` differed (cycle-4b
    # F-002). The compatible range (>= 3.8.9) is asserted inside
    # ``scripts/r_goldens/make_goldens_seqsurv.R``, where a mismatch stops
    # generation, and the resolved version is recorded in the provenance evidence
    # JSON by ``scripts/check_r_golden_provenance.py``.
    assert not _section(rows, "survival_version")

    summary = result.summary()
    assert list(summary.columns) == SUMMARY_COLUMNS
    expected_summary = []
    for key in keys:
        for values in _expected_curve(rows, key):
            expected_summary.append(
                {
                    "states": key,
                    "time": values[0],
                    "n.risk": values[1],
                    "n.event": values[2],
                    "surv": values[3],
                    "std.err": values[4],
                    "lower": values[5],
                    "upper": values[6],
                    "curve_axis": result.curve_axis,
                    "state": key if result.curve_axis == "state" else None,
                    "group": result.groups[0] if result.curve_axis == "state" else key,
                }
            )
    expected_frame = pd.DataFrame(expected_summary, columns=SUMMARY_COLUMNS)
    pd.testing.assert_frame_equal(
        summary, expected_frame, check_dtype=False, check_exact=False, rtol=0, atol=R_GOLDEN_ATOL
    )


@pytest.mark.parametrize(
    "case",
    [
        "state_all_unweighted",
        "state_all_weighted",
        "state_one_B",
        "state_subset_C_A",
        "state_one_group",
        "group_all_unweighted",
        "group_one_state_weighted",
        "group_subset_A_C",
        "missing_false",
    ],
)
def test_seqsurv_r2_routes_match_r_goldens(case):
    _assert_r2_result(case, _run_r2_case(case))


def test_seqsurv_with_missing_true_is_documented_full_python_extension(capsys):
    result = seqsurv(_r2_fixture(), state=["A", "*"], with_missing=True)
    assert result.states == ["A", "*"]
    assert list(result.curves) == ["A", "*"]
    assert all(curve.shape[1] == 7 for curve in result.curves.values())
    assert result.curves["*"].shape[0] == 1
    assert capsys.readouterr() == ("", "")

    # Upstream emits a misleading message and otherwise follows its false route.
    message = R2_MESSAGES.read_text(encoding="utf-8")
    assert "isn't implemented yet" in message
    false_rows = _case_rows("missing_false")
    true_rows = _case_rows("missing_true_r_route")
    for section in ("curve", "state", "group", "survival"):
        normalized_false = [
            {key: value for key, value in row.items() if key != "case"}
            for row in _section(false_rows, section)
        ]
        normalized_true = [
            {key: value for key, value in row.items() if key != "case"}
            for row in _section(true_rows, section)
        ]
        assert normalized_true == normalized_false


def test_seqsurv_legacy_direct_construction_and_empty_summary_schema():
    legacy = SeqSurv({"A": np.asarray([[1, 3, 1, 2 / 3, 0.2]], dtype=float)}, ["A"])
    summary = legacy.summary()
    assert list(summary.columns) == SUMMARY_COLUMNS
    assert np.isnan(summary.loc[0, "lower"])
    assert np.isnan(summary.loc[0, "upper"])
    assert summary.loc[0, "state"] == "A"
    assert summary.loc[0, "group"] == "1"

    empty = SeqSurv({"D": np.empty((0, 5), dtype=float)}, ["D"]).summary()
    assert empty.empty
    assert list(empty.columns) == SUMMARY_COLUMNS


@lru_cache(maxsize=1)
def _r2_errors():
    lines = R2_ERRORS.read_text(encoding="utf-8").splitlines()[1:]
    return dict(line.split("=", 1) for line in lines)


def test_seqsurv_refuses_multiple_groups_on_state_curve_route():
    expected = _r2_errors()["multi_group_state_route"]
    with pytest.raises(ValueError, match="only a single group is supported"):
        seqsurv(_r2_fixture(), groups=_groups(), per_state=False)
    assert "per.state = FALSE" in expected


def test_seqsurv_refuses_only_unobserved_states_and_non_sequence_input():
    with pytest.raises(ValueError, match="state contains only unobserved states"):
        seqsurv(_r2_fixture(), state=["U", "V"])
    assert "state contains only unobserved states" in _r2_errors()["unobserved_state"]

    with pytest.raises(TypeError, match="sequence object"):
        seqsurv(np.asarray([["A"]], dtype=object))
    assert "sequence object" in _r2_errors()["not_sequence"]
