def _interior_void_obj():
    # A A % B C * : an interior VOID ('%') + a trailing nr ('*'). R's seqdef rejects
    # a literal '%', but its seqformat unifies nr+void and re-derives interior
    # missing as nr -> the same SPELL output as R's interior-nr fixture (A A * B C *).
    return seqdef([["A", "A", "%", "B", "C", "*"]], alphabet=["A", "B", "C"], nr="*", void="%")


