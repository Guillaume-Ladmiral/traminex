    return np.column_stack(
        [
            df["id"].to_numpy(dtype=float),
            df["begin"].to_numpy(dtype=float),
            df["end"].to_numpy(dtype=float),
            np.asarray(df.attrs["state_code"], dtype=float),
        ]
    )


