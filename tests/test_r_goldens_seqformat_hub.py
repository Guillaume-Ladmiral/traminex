def _srs_matrix(x, df) -> np.ndarray:
    # Map state symbols to 1-based codes in the real alphabet (R: match(states, alphabet));
    # leading-NaN cells and void/nr symbols -> NaN, matching R's `match`.
    real_alph = [x.alphabet[i] for i in range(len(x.alphabet)) if i not in (x.void_code, x.nr_code)]
    code = {s: k + 1 for k, s in enumerate(real_alph)}
    out = np.empty(df.shape, dtype=float)
    out[:, 0] = df["id"].to_numpy(dtype=float)
    out[:, 1] = df["idx"].to_numpy(dtype=float)
    state_cols = [c for c in df.columns if c not in ("id", "idx")]
    for j, c in enumerate(state_cols):
        out[:, 2 + j] = [code.get(v, np.nan) if isinstance(v, str) else np.nan for v in df[c]]
    return out


def test_srs_A():
    x = fixture_a()
    assert_matches_golden(_srs_matrix(x, STS_to_SRS(x)), "seqformat_srs_A")
