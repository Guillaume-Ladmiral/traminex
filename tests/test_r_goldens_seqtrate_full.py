@pytest.mark.parametrize("case", list(STATIONARY_CASES))
def test_stationary_option_matrix_matches_r(case: str, stationary_golden: pd.DataFrame):
    builder, kwargs = STATIONARY_CASES[case]
    group = stationary_golden.loc[stationary_golden["case"] == case]
    assert not group.empty, f"missing R golden case {case}"
    from_states, to_states, expected = _stationary_expected(group)

    numeric = seqtrate(builder(), as_dataframe=False, **kwargs)
    assert isinstance(numeric, np.ndarray)
    assert numeric.shape == expected.shape
    np.testing.assert_allclose(numeric, expected, rtol=0, atol=ATOL)

    labelled = seqtrate(builder(), as_dataframe=True, **kwargs)
    assert isinstance(labelled, pd.DataFrame)
    assert labelled.index.tolist() == from_states
    assert labelled.columns.tolist() == to_states
    assert labelled.shape == expected.shape
    np.testing.assert_allclose(labelled.to_numpy(), expected, rtol=0, atol=ATOL)


def test_statl_is_a_warning_emitting_synonym(stationary_golden: pd.DataFrame):
    group = stationary_golden.loc[stationary_golden["case"] == "a_subset_ba_prob_lag1"]
    _, _, expected = _stationary_expected(group)
    with pytest.warns(DeprecationWarning, match="statl"):
        actual = seqtrate(fixture_a(), statl=["B", "A"], weighted=False, as_dataframe=False)
    np.testing.assert_allclose(actual, expected, rtol=0, atol=ATOL)


def test_statl_conflicts_with_sel_states():
    with pytest.raises(ValueError, match="statl.*sel_states|sel_states.*statl"):
        seqtrate(fixture_a(), sel_states=["A"], statl=["A"])


def test_empty_selected_states_preserves_r_refusal_boundary():
    with pytest.raises(ValueError, match="sel_states.*at least one"):
        seqtrate(fixture_a(), sel_states=[])


def test_scalar_multi_character_selected_state_is_not_split():
    x = seqdef(
        np.array([["Work", "Home"], ["Work", "Work"]], dtype=object),
        alphabet=["Work", "Home"],
    )
    scalar = seqtrate(x, sel_states="Work", weighted=False, as_dataframe=True)
    vector = seqtrate(x, sel_states=["Work"], weighted=False, as_dataframe=True)
    assert scalar.index.tolist() == ["Work"]
    pd.testing.assert_frame_equal(scalar, vector, check_exact=False, rtol=0, atol=R_GOLDEN_ATOL)


