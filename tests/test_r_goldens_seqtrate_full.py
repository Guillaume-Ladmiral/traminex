def _ordered(values: pd.Series) -> list[str]:
    return values.drop_duplicates().astype(str).tolist()


def _stationary_expected(group: pd.DataFrame) -> tuple[list[str], list[str], np.ndarray]:
    from_states = _ordered(group["from_state"])
    to_states = _ordered(group["to_state"])
    expected = np.empty((len(from_states), len(to_states)), dtype=float)
    from_index = {state: i for i, state in enumerate(from_states)}
    to_index = {state: i for i, state in enumerate(to_states)}
    for row in group.itertuples(index=False):
        expected[from_index[str(row.from_state)], to_index[str(row.to_state)]] = float(row.value)
    return from_states, to_states, expected


def _timevarying_expected(
    group: pd.DataFrame,
) -> tuple[list[str], list[str], list[str], np.ndarray]:
    from_states = _ordered(group["from_state"])
    to_states = _ordered(group["to_state"])
    time_labels = _ordered(group["time_label"])
    expected = np.empty((len(from_states), len(to_states), len(time_labels)), dtype=float)
    from_index = {state: i for i, state in enumerate(from_states)}
    to_index = {state: i for i, state in enumerate(to_states)}
    time_index = {label: i for i, label in enumerate(time_labels)}
    for row in group.itertuples(index=False):
        expected[
            from_index[str(row.from_state)],
            to_index[str(row.to_state)],
            time_index[str(row.time_label)],
        ] = float(row.value)
    return from_states, to_states, time_labels, expected


