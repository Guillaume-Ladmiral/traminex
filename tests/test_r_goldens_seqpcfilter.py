"""RP6b: live-R goldens for the seqpcfilter parallel-coordinate line filters.

Anchors traminex ``seqpcfilter`` line rules to TraMineR 2.2-14 ``minfreq`` /
``cumfreq`` / ``linear``. Goldens generated by
``scripts/r_goldens/make_goldens_seqpcfilter.R``.
"""

from __future__ import annotations

import numpy as np
import pytest
from r_goldens_utils import R_GOLDEN_ATOL, load_golden

from traminex.stats_p2 import seqpcfilter

X = [0.05, 0.15, 0.3, 0.1, 0.4]


def _check(actual, name):
    np.testing.assert_allclose(
        np.asarray(actual, dtype=float).ravel(),
        load_golden(name).ravel(),
        rtol=0,
        atol=R_GOLDEN_ATOL,
    )


def test_minfreq_01():
    _check(seqpcfilter("minfreq", level=0.1).apply(X), "seqpcfilter_minfreq_01")


def test_minfreq_02():
    _check(seqpcfilter("minfreq", level=0.2).apply(X), "seqpcfilter_minfreq_02")


def test_cumfreq_05():
    _check(seqpcfilter("cumfreq", level=0.5).apply(X), "seqpcfilter_cumfreq_05")


def test_cumfreq_075():
    _check(seqpcfilter("cumfreq", level=0.75).apply(X), "seqpcfilter_cumfreq_075")


def test_linear():
    _check(seqpcfilter("linear").apply(X), "seqpcfilter_linear")


def test_invalid_method():
    with pytest.raises(ValueError):
        seqpcfilter("nope")


def test_minfreq_requires_level():
    with pytest.raises(ValueError):
        seqpcfilter("minfreq", level=None)
