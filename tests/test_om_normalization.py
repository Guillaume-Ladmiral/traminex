def test_diagonal_is_zero(sts, base, norm):
    D = np.asarray(tx.seqdist(sts, norm=norm, **_BASE[base]), dtype=float)
    np.testing.assert_allclose(np.diag(D), np.zeros(D.shape[0]), rtol=0, atol=1e-12)


