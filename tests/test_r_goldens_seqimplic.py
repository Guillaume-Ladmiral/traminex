"""RP6b: live-R goldens for seqimplic (implicative statistics over positions).

Anchors traminex ``seqimplic`` to TraMineRextras 0.6.9. Goldens generated by
``scripts/r_goldens/make_goldens_seqimplic.R``.
"""

from __future__ import annotations

import numpy as np
from corestats_fixtures import fixture_a, fixture_b
from r_goldens_utils import R_GOLDEN_ATOL, load_golden

from traminex.stats_p2 import seqimplic

GROUP = [1, 1, 2, 2]


def _check(result, name):
    # R as.vector flattens column-major (level fastest); numpy 'F' order matches.
    np.testing.assert_allclose(
        result.indices.flatten(order="F"),
        load_golden(name).ravel(),
        rtol=0,
        atol=R_GOLDEN_ATOL,
        equal_nan=True,
    )


def test_seqimplic_A():
    _check(seqimplic(fixture_a(), GROUP), "seqimplic_A")


def test_seqimplic_A_weighted():
    _check(seqimplic(fixture_a(weighted=True), GROUP), "seqimplic_A_w")


def test_seqimplic_B_with_missing():
    _check(seqimplic(fixture_b(), GROUP, with_missing=True), "seqimplic_B_wm")
