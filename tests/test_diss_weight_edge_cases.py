"""R parity for non-finite and non-positive case weights in the ``diss*`` family.

Neither R nor traminex validates case weights on this path: ``dissvar`` hands
``as.double(weights)`` straight to ``C_tmrWeightedInertiaDist``
(``SOURCES/TraMineR/R/dissvar.R``). What the C kernel then does is specific and
easy to get wrong -- it guards **both** of its divisions with
``if (totweights>0)`` and otherwise returns the *undivided* sum
(``SOURCES/TraMineR/src/weightedinertia.cpp:34-38``). A NaN, Inf, all-negative or
zero-sum weight vector therefore reaches the caller as NaN / Inf / the raw sum,
never as a finite ``0.0``.

``disscenter`` compounds this: its C contribution is guarded the same way, but
the ``dc - weighted.mean(dc, weights)/2`` step in
``SOURCES/TraMineR/R/disscenter.R:87`` is **not**, so a zero or NaN total group
weight propagates into every member.

Goldens are generated by ``scripts/r_goldens/make_goldens_dissvar.R`` and
``scripts/r_goldens/make_goldens_disscenter.R`` against TraMineR 2.2-14.
"""

from __future__ import annotations

import numpy as np
import pytest
from r_goldens_utils import R_GOLDEN_ATOL, load_golden

from traminex.diss import disscenter, dissvar, dissvar_grp, weighted_inertia

# Row order of every golden in this module. Keep in step with the two generators.
WEIGHT_EDGE_CASES: dict[str, list[float]] = {
    "ones": [1.0, 1.0, 1.0],
    "varied": [2.0, 1.0, 3.0],
    "negative_middle": [1.0, -1.0, 1.0],
    "all_negative": [-1.0, -1.0, -1.0],
    "zeros": [0.0, 0.0, 0.0],
    "one_zero": [0.0, 1.0, 1.0],
    "sum_zero": [1.0, -1.0, 0.0],
    "inf_first": [np.inf, 1.0, 1.0],
    "nan_first": [np.nan, 1.0, 1.0],
    "nan_two": [np.nan, np.nan, 1.0],
    "nan_all": [np.nan, np.nan, np.nan],
    # A negative infinity is not the mirror of `inf_first`. The C kernel divides
    # by the total weight only under `if (totweights > 0)`
    # (SOURCES/TraMineR/src/weightedinertia.cpp:34), which -Inf fails, so R
    # returns the *undivided* sum and it keeps its sign; +Inf passes the guard
    # and collapses to Inf/Inf = NaN. The kernel's inner loop is strictly upper
    # triangular, so it never evaluates a diagonal `w_i * d_ii * w_i` and never
    # forms the +-Inf * 0 = NaN a whole-matrix product would.
    "neg_inf_middle": [1.0, -np.inf, 1.0],
    "neg_inf_all": [-np.inf, -np.inf, -np.inf],
    "mixed_inf": [np.inf, -np.inf, 1.0],
}
CASE_NAMES = list(WEIGHT_EDGE_CASES)

D = np.array([[0.0, 1.0, 2.0], [1.0, 0.0, 3.0], [2.0, 3.0, 0.0]])
GROUP = ["a", "a", "b"]


def _row(golden: str, case: str) -> np.ndarray:
    return load_golden(golden)[CASE_NAMES.index(case)]


@pytest.mark.parametrize("case", CASE_NAMES)
def test_dissvar_and_weighted_inertia_match_r_for_edge_weights(case):
    w = WEIGHT_EDGE_CASES[case]
    expected = _row("dissvar_weight_edge_cases", case)
    got = np.array(
        [
            dissvar(D, weights=w),
            dissvar(D, weights=w, squared=True),
            weighted_inertia(D, None, w),
        ]
    )
    np.testing.assert_allclose(got, expected, rtol=0, atol=R_GOLDEN_ATOL, equal_nan=True)


@pytest.mark.parametrize("case", CASE_NAMES)
def test_disscenter_single_group_matches_r_for_edge_weights(case):
    np.testing.assert_allclose(
        np.asarray(disscenter(D, weights=WEIGHT_EDGE_CASES[case]), dtype=float),
        _row("disscenter_weight_edge_cases_nogrp", case),
        rtol=0,
        atol=R_GOLDEN_ATOL,
        equal_nan=True,
    )


@pytest.mark.parametrize("case", CASE_NAMES)
def test_disscenter_grouped_matches_r_for_edge_weights(case):
    np.testing.assert_allclose(
        np.asarray(disscenter(D, group=GROUP, weights=WEIGHT_EDGE_CASES[case]), dtype=float),
        _row("disscenter_weight_edge_cases_grp", case),
        rtol=0,
        atol=R_GOLDEN_ATOL,
        equal_nan=True,
    )


@pytest.mark.parametrize("case", CASE_NAMES)
def test_disscenter_allcenter_matches_r_for_edge_weights(case):
    result = disscenter(D, group=GROUP, weights=WEIGHT_EDGE_CASES[case], allcenter=True)
    # R's data.frame is written column-major (group "a" then group "b").
    got = np.asarray(result, dtype=float).T.ravel()
    np.testing.assert_allclose(
        got,
        _row("disscenter_weight_edge_cases_allcenter", case),
        rtol=0,
        atol=R_GOLDEN_ATOL,
        equal_nan=True,
    )


def test_nan_weight_is_not_reported_as_a_finite_zero_discrepancy():
    # The specific shape of cycle-6 F-003: R signals NaN, traminex used to answer
    # 0.0 -- a plausible "this group has no variability at all".
    for w in ([np.nan, 1.0, 1.0], [np.nan, np.nan, 1.0], [np.nan, np.nan, np.nan]):
        assert np.isnan(dissvar(D, weights=w))
        assert np.isnan(weighted_inertia(D, None, w))
        assert np.isnan(np.asarray(disscenter(D, weights=w), dtype=float)).all()


def test_dissvar_grp_inherits_the_corrected_weight_handling():
    # traminex's dissvar_grp subsets the weight vector per group (a documented
    # difference from R, which forwards `...` unsubset and errors on a
    # single-member group), so it must inherit dissvar's propagation.
    out = dissvar_grp(D, GROUP, weights=[np.nan, 1.0, 1.0])
    assert np.isnan(out["a"])
    # Group "b" is a single case with a finite weight: R's own guarded kernel
    # returns the undivided sum, which is 0 for a 1x1 block.
    assert out["b"] == 0.0
