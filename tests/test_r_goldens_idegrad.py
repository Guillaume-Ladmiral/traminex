"""RP6b: live-R goldens for seqidegrad (degradation index) and seqinsecurity (type=2).

Anchors traminex ``seqidegrad`` / ``seqinsecurity`` to TraMineR 2.2-14. Goldens
generated by ``scripts/r_goldens/make_goldens_idegrad.R`` (reuses precarity A/B fixtures).
"""

from __future__ import annotations

import csv

import numpy as np
from corestats_fixtures import fixture_a, fixture_b
from r_goldens_utils import R_GOLDEN_ATOL, R_GOLDENS_DIR, load_golden

from traminex.stats_complexity import seqidegrad, seqinsecurity


def _check(actual, name):
    np.testing.assert_allclose(
        np.asarray(actual, dtype=float).ravel(),
        load_golden(name).ravel(),
        rtol=0,
        atol=R_GOLDEN_ATOL,
    )


def test_seqidegrad_A():
    _check(seqidegrad(fixture_a()), "seqidegrad_A")


def test_seqidegrad_A_tratedss():
    _check(seqidegrad(fixture_a(), method="TRATEDSS"), "seqidegrad_A_tratedss")


def test_seqidegrad_A_no_spell_integr():
    _check(seqidegrad(fixture_a(), spell_integr=False), "seqidegrad_A_nospell")


def test_seqidegrad_B_with_missing():
    _check(seqidegrad(fixture_b(), with_missing=True), "seqidegrad_B_wm")


def test_seqinsecurity_A():
    _check(seqinsecurity(fixture_a()), "seqinsecurity_A")


def test_seqinsecurity_A_bound():
    _check(seqinsecurity(fixture_a(), bound=True), "seqinsecurity_A_bound")


def test_seqinsecurity_B_with_missing():
    _check(seqinsecurity(fixture_b(), with_missing=True), "seqinsecurity_B_wm")


