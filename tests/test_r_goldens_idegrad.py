def _precarity_order_rows():
    with (R_GOLDENS_DIR / "precarity_order_r2_cases.csv").open(
        encoding="utf-8", newline=""
    ) as stream:
        return list(csv.DictReader(stream))


def _insecurity_fixture(tag):
    x = (
        fixture_b(weighted=tag.endswith("w"))
        if tag.startswith("B")
        else fixture_a(weighted=tag.endswith("w"))
    )
    return x


def test_seqinsecurity_r2_state_model_cross_product_matches_r_without_mutation():
    rows = [row for row in _precarity_order_rows() if row["function"] == "seqinsecurity"]
    cases = list(dict.fromkeys(row["case"] for row in rows))
    assert len(cases) == 7
    for case in cases:
        expected_rows = [row for row in rows if row["case"] == case]
        first = expected_rows[0]
        x = _insecurity_fixture(first["fixture"])
        before = x.copy()
        state_order = first["state_order"].split("|") if first["state_order"] else None
        state_equiv = (
            [group.split("+") for group in first["state_equiv"].split(";")]
            if first["state_equiv"]
            else None
        )
        correction_values = (
            np.asarray([float(item) for item in first["correction"].split("|")])
            if first["correction"]
            else None
        )
        actual = seqinsecurity(
            x,
            correction=correction_values,
            state_order=state_order,
            state_equiv=state_equiv,
            with_missing=first["with_missing"] == "TRUE",
            pow=float(first["pow"]),
            spow=float(first["spow"]),
            bound=first["bound"] == "TRUE",
            method=first["method"],
            penalized=first["penalized"],
            weight_type=first["weight_type"],
            border_effect=float(first["border_effect"]),
        )
        expected = np.asarray([float(row["value"]) for row in expected_rows])
        np.testing.assert_allclose(actual, expected, rtol=0, atol=R_GOLDEN_ATOL)
        np.testing.assert_array_equal(x.data, before.data)
        assert x.alphabet == before.alphabet
        if x.weights is not None:
            np.testing.assert_array_equal(x.weights, before.weights)
