"""RP6b: live-R goldens for seqsha (sequence-history person-period converter).

Anchors traminex ``seqsha`` to TraMineRextras 0.6.9. Goldens generated by
``scripts/r_goldens/make_goldens_seqsha.R``.
"""

from __future__ import annotations

import numpy as np
from corestats_fixtures import fixture_a
from r_goldens_utils import R_GOLDEN_ATOL, load_golden

from traminex.stats_p2 import seqsha

EVENT = [True, False, True, True]


def _matrix(df, x):
    real_alph = [x.alphabet[i] for i in range(len(x.alphabet)) if i not in (x.void_code, x.nr_code)]
    code = {s: k + 1 for k, s in enumerate(real_alph)}
    past_cols = [c for c in df.columns if c not in ("id", "time", "event")]
    out = np.empty((len(df), 3 + len(past_cols)), dtype=float)
    out[:, 0] = df["id"].to_numpy(dtype=float)
    out[:, 1] = df["time"].to_numpy(dtype=float)
    out[:, 2] = df["event"].to_numpy(dtype=float)
    for j, c in enumerate(past_cols):
        out[:, 3 + j] = [code.get(v, np.nan) if isinstance(v, str) else np.nan for v in df[c]]
    return out


def test_seqsha_start():
    x = fixture_a()
    df = seqsha(x, [3, 6, 2, 4], EVENT)
    np.testing.assert_allclose(
        _matrix(df, x), load_golden("seqsha_A_start"), rtol=0, atol=R_GOLDEN_ATOL, equal_nan=True
    )


def test_seqsha_end():
    x = fixture_a()
    df = seqsha(x, [3, 4, 2, 5], EVENT, align_end=True)
    np.testing.assert_allclose(
        _matrix(df, x), load_golden("seqsha_A_end"), rtol=0, atol=R_GOLDEN_ATOL, equal_nan=True
    )


def test_seqsha_end_present():
    x = fixture_a()
    df = seqsha(x, [3, 4, 2, 5], EVENT, align_end=True, include_present=True)
    np.testing.assert_allclose(
        _matrix(df, x),
        load_golden("seqsha_A_end_present"),
        rtol=0,
        atol=R_GOLDEN_ATOL,
        equal_nan=True,
    )
