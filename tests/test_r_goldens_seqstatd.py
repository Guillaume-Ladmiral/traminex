"""R-golden parity for seqstatd (T3) vs TraMineR 2.2-14.

Pins the per-position state distribution (Frequencies L x K), ValidStates and
normalized Entropy across the weighted (Aw), with.missing (B) and ragged/void
(C) paths. Goldens are generated by scripts/r_goldens/make_goldens_seqstatd.R.

R's statl is the real alphabet (+nr when with.missing) and NEVER includes the
structural void; traminex's STSList carries nr/void as trailing alphabet codes,
so the test selects the matching state columns (real states, + nr when
include_missing) and excludes void.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd
from corestats_fixtures import fixture_a, fixture_b, fixture_c
from r_goldens_utils import R_GOLDEN_ATOL, load_golden

from traminex.format import seqdef
from traminex.stats import seqstatd

R2_CASES = Path(__file__).with_name("r_goldens") / "seqstatd_r2_cases.csv"
R2_METADATA = Path(__file__).with_name("r_goldens") / "seqstatd_r2_metadata.txt"
R2_NUMERIC_CASES = {
    "A_unweighted_norm",
    "A_unweighted_raw_entropy",
    "Aw_weighted_norm",
    "Aw_weighted_raw_entropy",
    "B_wm0",
    "B_wm1",
    "C_ragged_wm0",
    "C_ragged_wm1",
    "declared_nr_absent",
    "all_void",
}


def _state_cols(x, include_missing: bool):
    """Column indices matching R's statl: real states, + nr if with.missing, no void."""
    return [
        i
        for i in range(len(x.alphabet))
        if i != x.void_code and (include_missing or i != x.nr_code)
    ]


def _check(x, tag: str, include_missing: bool):
    out = seqstatd(x, include_missing=include_missing)
    cols = _state_cols(x, include_missing)
    freq = np.asarray(out["Frequencies"], dtype=float)[:, cols]
    np.testing.assert_allclose(
        freq, load_golden(f"seqstatd_{tag}_freq"), rtol=0, atol=R_GOLDEN_ATOL
    )
    ve = load_golden(f"seqstatd_{tag}_ve")
    np.testing.assert_allclose(
        np.asarray(out["ValidStates"], dtype=float), ve[0], rtol=0, atol=R_GOLDEN_ATOL
    )
    np.testing.assert_allclose(
        np.asarray(out["Entropy"], dtype=float), ve[1], rtol=0, atol=R_GOLDEN_ATOL
    )


def test_seqstatd_a_unweighted():
    _check(fixture_a(), "A", False)


def test_seqstatd_a_weighted():
    _check(fixture_a(weighted=True), "Aw", False)


def test_seqstatd_b_with_and_without_missing():
    _check(fixture_b(), "B_wm0", False)
    _check(fixture_b(), "B_wm1", True)


def test_seqstatd_c_ragged_with_and_without_missing():
    _check(fixture_c(), "C_wm0", False)
    _check(fixture_c(), "C_wm1", True)


def _r2_inputs():
    declared_nr_absent = seqdef(
        np.array([["A", "B"], ["B", "A"]], dtype=object),
        alphabet=["A", "B"],
        nr="*",
    )
    declared_nr_absent.nr_code = len(declared_nr_absent.alphabet)
    declared_nr_absent.alphabet.append("*")
    if declared_nr_absent.labels is not None:
        declared_nr_absent.labels.append("*")
    if declared_nr_absent.cpal is not None:
        declared_nr_absent.cpal.append(declared_nr_absent.missing_color)
    all_void = fixture_c()
    assert all_void.void_code is not None
    all_void.data[:] = all_void.void_code
    return {
        "A_unweighted_norm": (fixture_a(weighted=True), False, False, True),
        "A_unweighted_raw_entropy": (fixture_a(weighted=True), False, False, False),
        "Aw_weighted_norm": (fixture_a(weighted=True), True, False, True),
        "Aw_weighted_raw_entropy": (fixture_a(weighted=True), True, False, False),
        "B_wm0": (fixture_b(), True, False, True),
        "B_wm1": (fixture_b(), True, True, True),
        "C_ragged_wm0": (fixture_c(), True, False, True),
        "C_ragged_wm1": (fixture_c(), True, True, True),
        "declared_nr_absent": (declared_nr_absent, True, True, True),
        "all_void": (all_void, True, False, True),
    }


def _metadata_by_case() -> dict[str, dict[str, str]]:
    frame = pd.read_csv(R2_METADATA, sep="\t", dtype=str, keep_default_na=False)
    return {
        case: dict(zip(group["field"], group["value"], strict=True))
        for case, group in frame.groupby("case", sort=False)
    }


def test_seqstatd_r2_manifest_has_the_exact_case_sets():
    frame = pd.read_csv(R2_CASES)
    assert set(frame["case"]) == R2_NUMERIC_CASES
    assert set(_metadata_by_case()) == R2_NUMERIC_CASES | {"zero_width"}
    assert _metadata_by_case()["zero_width"] == {"error": "undefined columns selected"}


def test_seqstatd_r2_values_and_metadata_match_r():
    frame = pd.read_csv(R2_CASES)
    metadata = _metadata_by_case()
    inputs = _r2_inputs()
    assert set(inputs) == R2_NUMERIC_CASES

    for case, (x, weighted, include_missing, norm) in inputs.items():
        result = seqstatd(
            x,
            weighted=weighted,
            include_missing=include_missing,
            norm=norm,
        )
        expected = frame.loc[frame["case"] == case].reset_index(drop=True)
        state_indexes = [x.alphabet.index(state) for state in expected["state"]]
        time_indexes = expected["time_index"].to_numpy(dtype=int) - 1
        observed_frequency = result["Frequencies"][time_indexes, state_indexes]
        np.testing.assert_allclose(
            observed_frequency,
            expected["value"].to_numpy(dtype=float),
            rtol=0,
            atol=R_GOLDEN_ATOL,
            equal_nan=True,
        )
        np.testing.assert_allclose(
            result["ValidStates"][time_indexes],
            expected["valid_states"].to_numpy(dtype=float),
            rtol=0,
            atol=R_GOLDEN_ATOL,
        )
        np.testing.assert_allclose(
            result["Entropy"][time_indexes],
            expected["entropy"].to_numpy(dtype=float),
            rtol=0,
            atol=R_GOLDEN_ATOL,
            equal_nan=True,
        )

        case_metadata = metadata[case]
        assert result.nbseq == float(case_metadata["nbseq"])
        assert result.weighted is (case_metadata["weighted"] == "TRUE")
        assert result.norm is (case_metadata["norm"] == "TRUE")
        assert result.xtlab == case_metadata["xtlab"].split("|")
        assert result.xtstep == int(case_metadata["xtstep"])
        assert result.tick_last is (case_metadata["tick.last"] == "TRUE")
        assert result.cpal == case_metadata["cpal"].split("|")


def test_seqstatd_result_remains_a_mutable_three_key_mapping():
    result = seqstatd(fixture_a())
    assert list(result) == ["Frequencies", "ValidStates", "Entropy"]
    assert type(result).__name__ == "SeqStatDResult"

    marker = np.array([42.0])
    result["marker"] = marker
    result.update({"updated": marker})
    assert result["marker"] is marker
    assert result["updated"] is marker

    copied = result.copy()
    assert type(copied) is dict
    assert copied["Frequencies"] is result["Frequencies"]
    assert list(iter(result)) == [
        "Frequencies",
        "ValidStates",
        "Entropy",
        "marker",
        "updated",
    ]


def test_seqstatd_weighted_false_ignores_attached_and_explicit_weights():
    x = fixture_a(weighted=True)
    baseline = seqstatd(x, weighted=False)
    overridden = seqstatd(x, weighted=False, weights=np.array([9.0, 1.0, 1.0, 1.0]))
    for key in baseline:
        np.testing.assert_array_equal(overridden[key], baseline[key])
    assert overridden.nbseq == x.nseq
    assert overridden.weighted is False


def test_seqstatd_zero_width_preserves_the_safe_python_result():
    x = fixture_a(weighted=True)
    x.data = x.data[:, :0]
    result = seqstatd(x)
    assert result["Frequencies"].shape == (0, len(x.alphabet))
    assert result["ValidStates"].shape == (0,)
    assert result["Entropy"].shape == (0,)
    assert result.xtlab == []
