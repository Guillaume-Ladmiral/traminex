"""Shared helpers for R-golden parity tests (migration plan Phase 0.1).

The acceptance test for every migration item is agreement with the original
R source — TraMineR 2.2-14 / TraMineRextras 0.6.9, see the pinned versions in
``DUPLICATES.md`` — not with any Python copy.

Golden matrices are generated by the scripts in ``scripts/r_goldens/`` against
the vendored R packages (values dumped with ``%.15g``) and stored either

- inline in a test module (existing pattern, see
  ``test_r_goldens_distances.py``), or
- as one CSV file per golden in ``tests/r_goldens/`` (pattern for new goldens,
  e.g. the Phase 2 ``dissvar`` / ``dissassoc`` / ``disscenter`` / ``disstree``
  work), loaded through :func:`load_golden`.

Each golden CSV may start with ``#`` comment lines recording the exact R call
that produced it; keep those lines when regenerating.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

R_GOLDENS_DIR = Path(__file__).resolve().parent / "r_goldens"

# Default absolute tolerance when comparing traminex output to R goldens
# dumped with %.15g (same tolerance as test_r_goldens_distances.py).
R_GOLDEN_ATOL = 1e-10

#: The smallest difference a "values differ" check (``not np.allclose``, ``!= approx``)
#: accepts as real: far above the rounding R_GOLDEN_ATOL allows, far below the differences
#: those checks assert (0.2 or more where measured, batch-16 review M-5). With the equality
#: tolerance a negated comparison would pass on a difference of 1e-10.
R_DIFFERENCE_ATOL = 1e-6


def _to_float(token: str) -> float:
    """Parse one R-dumped numeric token, mapping R's NA/NaN/Inf to numpy floats."""
    t = token.strip()
    low = t.lower()
    if low in ("na", "nan"):
        return float("nan")
    if low in ("inf", "+inf"):
        return float("inf")
    if low == "-inf":
        return float("-inf")
    return float(t)


def parse_r_matrix(text: str) -> np.ndarray:
    """Parse a comma-separated numeric matrix dumped from R.

    Blank lines and ``#`` comment lines are ignored, so golden files can carry
    the generating R call in their header.
    """
    rows = []
    for line in text.strip().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        rows.append([_to_float(v) for v in line.split(",")])
    if not rows:
        raise ValueError("no numeric rows found in R golden text")
    return np.array(rows, dtype=float)


def load_golden(name: str) -> np.ndarray:
    """Load ``tests/r_goldens/<name>.csv`` as a float matrix."""
    path = R_GOLDENS_DIR / f"{name}.csv"
    if not path.is_file():
        raise FileNotFoundError(
            f"R golden '{name}' not found at {path}. Generate it with the scripts in "
            "scripts/r_goldens/ against the R versions pinned in DUPLICATES.md."
        )
    return parse_r_matrix(path.read_text(encoding="utf-8"))


def load_golden_text(name: str, ext: str = ".txt") -> str:
    """Load ``tests/r_goldens/<name><ext>`` verbatim (for string / dot structure goldens)."""
    path = R_GOLDENS_DIR / f"{name}{ext}"
    if not path.is_file():
        raise FileNotFoundError(
            f"R text golden '{name}{ext}' not found at {path}. Generate it with the scripts in "
            "scripts/r_goldens/ against the R versions pinned in DUPLICATES.md."
        )
    return path.read_text(encoding="utf-8")


def load_golden_lines(name: str, ext: str = ".txt") -> list[str]:
    """Load a text golden as a list of lines (trailing newline stripped, blanks kept)."""
    text = load_golden_text(name, ext)
    return text.splitlines()


def r_anchor(case: str, kind: str) -> list[str]:
    """One recorded R result from ``tests/r_goldens/inline_r_anchors.txt``.

    Written by ``scripts/r_goldens/make_goldens_audit20260922_s10.R`` for the
    tests that used to carry these R values inline. ``kind`` is ``"values"``,
    ``"error"``, ``"strings"``, ``"dim"`` or ``"length"``; the fields are
    returned as text, with R's newlines restored.
    """
    for line in load_golden_lines("inline_r_anchors"):
        if line.startswith("#"):
            continue
        recorded_case, recorded_kind, *fields = line.split("\t")
        if (recorded_case, recorded_kind) == (case, kind):
            return [field.replace("\\n", "\n") for field in fields]
    raise KeyError(f"no recorded R {kind!r} for {case!r} in inline_r_anchors.txt")


def r_anchor_values(case: str) -> np.ndarray:
    """A recorded R numeric result (column-major) as a float array."""
    return np.array([_to_float(field) for field in r_anchor(case, "values")], dtype=float)


def r_anchor_shape(case: str) -> tuple[int, ...]:
    """R's ``dim()`` of a recorded result, or ``(length,)`` for a plain vector."""
    for kind in ("dim", "length"):
        try:
            return tuple(int(field) for field in r_anchor(case, kind))
        except KeyError:
            continue
    raise KeyError(f"no recorded R shape for {case!r} in inline_r_anchors.txt")


def assert_matches_golden(actual, name: str, *, atol: float = R_GOLDEN_ATOL) -> None:
    """Assert that ``actual`` equals the named R golden within ``atol``."""
    golden = load_golden(name)
    actual = np.asarray(actual, dtype=float)
    assert (
        actual.shape == golden.shape
    ), f"shape {actual.shape} != golden shape {golden.shape} for '{name}'"
    np.testing.assert_allclose(actual, golden, rtol=0, atol=atol)
